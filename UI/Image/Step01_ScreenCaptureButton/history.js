// ======================================================
// Canvas
// ======================================================

import { canvases, contexts } from "./canvas.js";

// ======================================================
// 描画履歴
// ======================================================

const drawingHistory = [];

// ======================================================
// Redo履歴
// ======================================================

const redoHistory = [];

// ======================================================
// 履歴へ追加
// ======================================================
//
// type:
// "stroke" = 手描き
// "image"  = 画像
// ======================================================

function addHistory(item) {
  if (!item) {
    return;
  }

  drawingHistory.push(item);

  // ==================================================
  // 新しい操作を行ったらRedo履歴を消去
  // ==================================================

  redoHistory.length = 0;
}

// ======================================================
// 手描きを履歴へ追加
// ======================================================

function addStroke(stroke) {
  if (!stroke) {
    return;
  }

  stroke.type = "stroke";

  addHistory(stroke);
}

// ======================================================
// 画像を履歴へ追加
// ======================================================

function addImage(imageData) {
  if (!imageData) {
    return;
  }

  imageData.type = "image";

  addHistory(imageData);
}

// ======================================================
// Canvasを履歴から再描画
// ======================================================

function redrawAll() {
  // ==================================================
  // 全Layerを消去
  // ==================================================

  contexts.forEach((ctx, index) => {
    ctx.clearRect(0, 0, canvases[index].width, canvases[index].height);
  });

  // ==================================================
  // 履歴から再描画
  // ==================================================

  drawingHistory.forEach((item) => {
    if (!item) {
      return;
    }

    // ==================================================
    // Layer番号
    // ==================================================

    const layerIndex = item.layerIndex ?? 0;

    if (layerIndex < 0 || layerIndex >= contexts.length) {
      return;
    }

    const ctx = contexts[layerIndex];

    // ==================================================
    // 手描き
    // ==================================================

    if (item.type === "stroke") {
      if (!item.points || item.points.length === 0) {
        return;
      }

      ctx.beginPath();

      ctx.moveTo(item.points[0].x, item.points[0].y);

      for (let i = 1; i < item.points.length; i++) {
        ctx.lineTo(item.points[i].x, item.points[i].y);
      }

      ctx.stroke();

      return;
    }

    // ==================================================
    // 画像
    // ==================================================

    if (item.type === "image") {
      if (!item.imageData) {
        return;
      }

      const image = new Image();

      image.onload = () => {
        ctx.drawImage(
          image,
          0,
          0,
          canvases[layerIndex].width,
          canvases[layerIndex].height,
        );
      };

      image.onerror = () => {
        console.error("画像の読み込みに失敗しました");
      };

      image.src = item.imageData;
    }
  });
}

// ======================================================
// 初期化
// ======================================================

function initializeDrawing() {
  // ==================================================
  // 描画履歴を消去
  // ==================================================

  drawingHistory.length = 0;

  // ==================================================
  // Redo履歴を消去
  // ==================================================

  redoHistory.length = 0;

  // ==================================================
  // Canvasを再描画
  // ==================================================

  redrawAll();
}

// ======================================================
// Undo
// ======================================================

function undoDrawing() {
  if (drawingHistory.length === 0) {
    return;
  }

  // ==================================================
  // 最後の操作を取り出す
  // ==================================================

  const item = drawingHistory.pop();

  // ==================================================
  // Redo履歴へ移動
  // ==================================================

  redoHistory.push(item);

  // ==================================================
  // 履歴から再描画
  // ==================================================

  redrawAll();
}

// ======================================================
// Redo
// ======================================================

function redoDrawing() {
  if (redoHistory.length === 0) {
    return;
  }

  // ==================================================
  // Redo履歴から取り出す
  // ==================================================

  const item = redoHistory.pop();

  // ==================================================
  // 描画履歴へ戻す
  // ==================================================

  console.log("Redo:", item);

  drawingHistory.push(item);

  // ==================================================
  // 履歴から再描画
  // ==================================================

  redrawAll();
}

// ======================================================
// 外部へ公開
// ======================================================

export {
  drawingHistory,
  redoHistory,
  addHistory,
  addStroke,
  addImage,
  redrawAll,
  initializeDrawing,
  undoDrawing,
  redoDrawing,
};
