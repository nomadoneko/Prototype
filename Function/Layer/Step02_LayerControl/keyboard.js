// ======================================================
// Layer
// ======================================================

import {
  switchLayer,
  toggleLayerVisibility,
  toggleAllLayerVisibility
} from "./layer.js";


// ======================================================
// History
// ======================================================

import {
  undoDrawing,
  redoDrawing
} from "./history.js";


// ======================================================
// キーボード操作
// ======================================================

document.addEventListener("keydown", (e) => {

  // ==================================================
  // Layer 1
  // ==================================================

  if (e.key === "1") {

    switchLayer(0);

    return;
  }


  // ==================================================
  // Layer 2
  // ==================================================

  if (e.key === "2") {

    switchLayer(1);

    return;
  }


  // ==================================================
  // Layer 3
  // ==================================================

  if (e.key === "3") {

    switchLayer(2);

    return;
  }


  // ==================================================
  // Ctrl + Z
  // ==================================================

  if (e.ctrlKey && e.key.toLowerCase() === "z") {

    e.preventDefault();

    undoDrawing();

    return;
  }


  // ==================================================
  // Ctrl + Y
  // ==================================================

  if (e.ctrlKey && e.key.toLowerCase() === "y") {

    e.preventDefault();

    redoDrawing();

    return;
  }


  // ==================================================
  // V → 現在Layerの表示 / 非表示
  // ==================================================

  if (e.key.toLowerCase() === "v") {

    toggleLayerVisibility();

    return;
  }


  // ==================================================
  // A → 全Layerの表示 / 非表示
  // ==================================================

  if (e.key.toLowerCase() === "a") {

    toggleAllLayerVisibility();

    return;
  }

});