// ======================================================
// Canvas
// ======================================================

import {
  canvases,
  contexts
} from "./canvas.js";


// ======================================================
// 描画履歴
// ======================================================

const drawingHistory = [];


// ======================================================
// Redo履歴
// ======================================================

const redoHistory = [];


// ======================================================
// 描画を履歴へ追加
// ======================================================

function addStroke(stroke) {

  if (!stroke) {
    return;
  }

  drawingHistory.push(stroke);

  // ==================================================
  // 新しい描画を行ったらRedo履歴を消去
  // ==================================================

  redoHistory.length = 0;

}


// ======================================================
// Canvasを履歴から再描画
// ======================================================

function redrawAll() {

  // ==================================================
  // 全Layerを消去
  // ==================================================

  contexts.forEach((ctx, index) => {

    ctx.clearRect(
      0,
      0,
      canvases[index].width,
      canvases[index].height
    );

  });


  // ==================================================
  // 履歴から再描画
  // ==================================================

  drawingHistory.forEach((stroke) => {

    if (
      !stroke.points ||
      stroke.points.length === 0
    ) {
      return;
    }


    // ==================================================
    // Layer番号を取得
    // ==================================================

    const layerIndex =
      stroke.layerIndex ?? 0;


    if (
      layerIndex < 0 ||
      layerIndex >= contexts.length
    ) {
      return;
    }


    const ctx =
      contexts[layerIndex];


    // ==================================================
    // ストロークを再描画
    // ==================================================

    ctx.beginPath();

    ctx.moveTo(
      stroke.points[0].x,
      stroke.points[0].y
    );


    for (
      let i = 1;
      i < stroke.points.length;
      i++
    ) {

      ctx.lineTo(
        stroke.points[i].x,
        stroke.points[i].y
      );

    }


    ctx.stroke();

  });

}


// ======================================================
// 初期化
// ======================================================

function initializeDrawing() {

  // ==================================================
  // 描画履歴を消去
  // ==================================================

  drawingHistory.length = 0;


  // ==================================================
  // Redo履歴を消去
  // ==================================================

  redoHistory.length = 0;


  // ==================================================
  // Canvasを再描画
  // ==================================================

  redrawAll();

}


// ======================================================
// Undo
// ======================================================

function undoDrawing() {

  if (drawingHistory.length === 0) {
    return;
  }


  // ==================================================
  // 最後の描画を取り出す
  // ==================================================

  const stroke =
    drawingHistory.pop();


  // ==================================================
  // Redo履歴へ移動
  // ==================================================

  redoHistory.push(stroke);


  // ==================================================
  // 履歴から再描画
  // ==================================================

  redrawAll();

}


// ======================================================
// Redo
// ======================================================

function redoDrawing() {

  if (redoHistory.length === 0) {
    return;
  }


  // ==================================================
  // Redo履歴から取り出す
  // ==================================================

  const stroke =
    redoHistory.pop();


  // ==================================================
  // 描画履歴へ戻す
  // ==================================================

  drawingHistory.push(stroke);


  // ==================================================
  // 履歴から再描画
  // ==================================================

  redrawAll();

}


// ======================================================
// 外部へ公開
// ======================================================

export {
  drawingHistory,
  redoHistory,
  addStroke,
  redrawAll,
  initializeDrawing,
  undoDrawing,
  redoDrawing
};